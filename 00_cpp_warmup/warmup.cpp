#include <cstdio>

// ===========================================================================
// 第 3 部分会用到这两个函数，先声明在这里
// ===========================================================================
void changeByValue(int x) { x = 999; }          // 收下的是复印件
void changeByPointer(int* p) { *p = 999; }      // 收下的是地址，能改原件

int main() {
    printf("==================================================\n");
    printf(" 第 1 部分：变量、地址、指针\n");
    printf("==================================================\n");

    // 把内存想象成一条街，每家房子有个门牌号。
    // 变量 = 房子里放的东西，地址 = 门牌号，指针 = 一张写着门牌号的纸条。

    int a = 42;
    printf("a 的值        : %d\n", a);
    printf("a 的门牌号     : %p\n", (void*)&a);

    int* p = &a;                          // p 是一张纸条，上面抄了 a 的门牌号
    printf("纸条上写的     : %p\n", (void*)p);
    printf("顺着纸条取东西 : %d   ← 这就是 *p，叫「解引用」\n", *p);

    *p = 100;                             // 顺着纸条去那家房子，把东西换掉
    printf("顺着纸条改完后 a = %d  ← a 真的变了，因为改的就是它家\n\n", a);

    // 小结：& 是「取门牌号」，* 是「按门牌号上门」

    printf("==================================================\n");
    printf(" 第 2 部分：数组就是一条街上挨着的几套房\n");
    printf("==================================================\n");

    float arr[5] = {1.0f, 2.0f, 3.0f, 4.0f, 5.0f};
    printf("arr[0] = %.1f, arr[4] = %.1f\n", arr[0], arr[4]);

    printf("arr[0] 的门牌号: %p\n", (void*)&arr[0]);
    printf("arr[1] 的门牌号: %p   ← 比 arr[0] 大 4，因为 float 占 4 字节\n",
           (void*)&arr[1]);

    // 关键：arr 这个名字本身就等于首地址
    float* q = arr;
    printf("q = arr 之后，*q = %.1f\n", *q);
    printf("*(q + 2) = %.1f   ← 往后走两户，就是 arr[2]\n", *(q + 2));

    // 这就是为什么 GPU 里能用 a[i] 访问数组：
    //   a[i]  本质上是  *(a + i)
    // 「往后走 i 户」这个动作，在显存里就是「地址加 i × 4 字节」。
    // 昨天说的「合并访问」，就是指一排线程分别访问挨着的几户 —— 显存一次能搬一整条。
    printf("\n");

    printf("==================================================\n");
    printf(" 第 3 部分：函数传参，为什么 CUDA 到处是 &\n");
    printf("==================================================\n");

    int b = 1;
    changeByValue(b);
    printf("按值传参后 b = %d   ← 没变！函数改的是复印件\n", b);

    changeByPointer(&b);
    printf("按地址传参后 b = %d  ← 变了！函数顺着门牌号改到了原件\n", b);

    // cudaMalloc(&d_x, bytes) 是同一回事：
    //   它要在「你的 d_x 这个变量」里写入一个新地址，
    //   所以必须把 d_x 的门牌号交给它，它才够得着你的变量。
    // 如果不加 &，它只能改一个复印件，你的 d_x 永远是空指针。
    printf("\n");

    printf("==================================================\n");
    printf(" 第 4 部分：const 放在哪，管的东西不一样\n");
    printf("==================================================\n");

    int m = 10, n = 20;

    const int* p1 = &m;     // 「指向的内容」不能改，指针自己可以改指向别人
    p1 = &n;                // 合法
    // *p1 = 99;            // 非法：不许通过 p1 改内容
    printf("const int*  : 能换指向，不能改内容。现在 *p1 = %d\n", *p1);

    int* const p2 = &m;     // 「指针自己」不能改，但内容可以改
    *p2 = 99;               // 合法
    // p2 = &n;             // 非法：不许换指向
    printf("int* const  : 不能换指向，能改内容。现在 m = %d\n", m);

    // 口诀：const 在 * 左边 —— 管内容；const 在 * 右边 —— 管指针。
    //
    // kernel 里的写法就有意义了：
    //   const float* x   → 我不能通过 x 改动输入数据（只读）
    //   float* y         → 我可以改 y 指向的数据（原地修改）
    printf("\n");

    printf("==================================================\n");
    printf(" 第 5 部分：循环累加 —— 你早就会，只是确认一下\n");
    printf("==================================================\n");

    float data[5] = {1.5f, 2.5f, 3.5f, 4.5f, 5.5f};
    float sum = 0.0f;
    for (int i = 0; i < 5; ++i) {       // i 从 0 开始，这是编程的惯例
        sum += data[i];
    }
    printf("累加结果 = %.1f  （应该是 17.5）\n", sum);

    // CUDA kernel 里那个 for 循环一模一样，只是加了 stride：
    //   for (int i = idx; i < n; i += stride)
    // 起点是 idx（我的编号），每次多走 stride 户，走出数组范围就停。
    printf("\n完成。看懂这五段，saxpy.cu 你就能读了。\n");

    return 0;
}
